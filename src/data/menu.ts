export function filterMenu(items: Dish[], category: Category, dietary: Dietary): Dish[] {
  return items.filter(
    (dish) =>
      (category === "All" || dish.category === category) &&
      (dietary === "All vegetarian" || (dietary === "Vegan" ? dish.vegan : dish.glutenFree)),
  );
}

export const formatPrice = (price: number) =>
  new Intl.NumberFormat("en-US", {
    style: "currency",
    currency: "USD",
    maximumFractionDigits: price % 1 ? 2 : 0,
  }).format(price);
